def test_every_remedy_flag_value_in_a_manifest_is_one_the_trainer_knows():
    for name in V2_FILES + V3_FILES:
        for r in _rows(name):
            assert r["adv_variant"] in RW.ADV_VARIANTS and r["group_filter"] in RW.GROUP_FILTERS
    # The v4 manifest is the first to name the verdict variant, which the trainer accepts and the
    # rewards-only analysis signature does not.
    for name in V4_FILES:
        for r in _rows(name):
            assert r["adv_variant"] in RW.TRAINER_ADV_VARIANTS and r["group_filter"] in RW.GROUP_FILTERS
            assert float(r["fixedref_c"]) == (2.0 if r["adv_variant"] == "grpo_fixedref" else 0.0)
            assert int(r["group_size"]) in (4, 8) and r["skip_zero_adv"] in ("0", "1")


def test_a_stale_schedule_entry_is_refused_by_the_manifest_generator(tmp_path, monkeypatch):
    """Each v3 row must agree with the committed schedule entry, so a schedule file whose entry
    describes another run stops the generator before it writes a row."""
    import json
    import shutil
    (tmp_path / "slurm").mkdir()
    (tmp_path / "configs").mkdir()
    for name in ("manifest_speed_remedy.csv", "manifest_capacity_remedy.csv"):
        shutil.copy(os.path.join(HERE, "slurm", name), tmp_path / "slurm" / name)
    doc = json.loads(open(os.path.join(HERE, "configs", "keep_schedules.json")).read())
    doc["schedules"]["speed_w5_s0_d0"]["vmax"] = 6.0
    (tmp_path / "configs" / "keep_schedules.json").write_text(json.dumps(doc))
    monkeypatch.setattr(M, "HERE", tmp_path)
    assert len(M.capacity_yoked()) == 6
    with pytest.raises(ValueError, match="speed_w5_s0_d0"):
        M.speed_yoked()
