def test_seeds_three_and_four_follow_the_ledger_priority_order():
    rows = _rows("manifest_capacity.csv")
    legacy = {(r["regime"], r["arm_name"]): r for r in rows[:36]}
    new = rows[36:]
    assert len(new) == 24
    assert set(Counter((r["regime"], r["arm_name"]) for r in new).values()) == {2}
    regimes = [r["regime"] for r in new]
    assert regimes == ["H"] * 12 + ["E"] * 12, "every hard-level row comes before the easy level"
    easy_task_weights = [float(r["w_task"]) for r in new[12:]]
    assert easy_task_weights == sorted(easy_task_weights, reverse=True), \
        "easy-level arms with a task term come before the arms without one"
    assert [r["arm_name"] for r in new[20:]][::2] == ["verdict_only", "graded_no_task"]
    for r in new:
        base = legacy[(r["regime"], r["arm_name"])]
        assert {k: v for k, v in r.items() if k not in ("task_id", "seed")} == \
            {k: v for k, v in base.items() if k not in ("task_id", "seed")}
    assert [int(r["seed"]) for r in new] == [3, 4] * 12


