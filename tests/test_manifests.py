"""The revision's manifests and the submission script's v2, v3 and v4 branches.

The manifests decide which runs exist, so they are generated by make_manifests.py and checked here
against that output. The submission script passes the remedy flags only for the v2, v3 and v4 layouts,
and it passes the keep schedule only for the v3 layout. A script that passed them for a v1 row, or
dropped them for a v2 or v3 row, would run a different arm from the one its directory name claims.

The v4 layout (ICML 2027, November 2026) is the v2 layout followed by the fixed-reference shift, the
zero-advantage skip and the group size. Only the v4 branch passes those three, and it passes the skip
only when the field is 1. The v4 branch sits after the v3 branch, and the v2, v3 and v1 branches are
pinned byte for byte. The v4 manifest itself, slurm/manifest_speed_bounded.csv, is checked in
tests/test_speed_bounded.py against make_bounded_manifest.py.
"""
