def _branches():
    """The parse block split into its branches: v2, v3, v4 and the v1 tail, each as its own text."""
    block = _parse_block()
    after_v2 = block.split(V2_HEAD)[1]
    v2 = after_v2.split("elif ")[0]
    assert after_v2.split("elif ", 1)[1].startswith(V3_HEAD[len("elif "):]), \
        "the v3 branch must come right after the v2 branch"
    after_v3 = after_v2.split(V3_HEAD)[1]
    v3 = after_v3.split("elif ")[0]
    assert after_v3.split("elif ", 1)[1].startswith(V4_HEAD[len("elif "):]), \
        "the v4 branch must come right after the v3 branch"
    after_v4 = after_v3.split(V4_HEAD)[1]
    v4 = after_v4.split("elif ")[0]
    v1 = "elif " + after_v4.split("elif ", 1)[1]
    return v2, v3, v4, v1


@requires_sbatch
def test_the_v2_branch_bytes_are_unchanged():
    block = _parse_block()
    v2 = block.split(V2_HEAD)[1].split("elif ")[0]
    assert hashlib.sha256(v2.encode()).hexdigest() == V2_BRANCH_SHA256
    assert _branches()[0] == v2


@requires_sbatch
def test_the_v3_branch_and_the_v1_tail_bytes_are_unchanged():
    _, v3, _, v1 = _branches()
    assert hashlib.sha256(v3.encode()).hexdigest() == V3_BRANCH_SHA256
    assert hashlib.sha256(v1.encode()).hexdigest() == V1_TAIL_SHA256


