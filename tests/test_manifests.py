@requires_sbatch
def test_the_bounded_task_takes_the_speed_task_s_generation_length_backward_form_and_wall_clock():
    """Outside the parse block the script sets three things by task. The bounded speed task answers
    with one integer, so it must take the speed values for all three."""
    src = open(SBATCH).read()
    # the three original lines, which tests/test_matched_budget.py reads by regex, are unchanged
    original = ('if [ "${CANCEL_TASK}" = "speed" ]; then MAXTOK=6; else MAXTOK=128; fi',
                'if [ "${CANCEL_TASK}" != "speed" ]; then BWD_FLAG="--backward-per-group"; fi',
                'if [ "${CANCEL_TASK}" != "speed" ]; then NEED_MIN=120; fi')
    override = ('if [ "${CANCEL_TASK}" = "speed_bounded" ]; then MAXTOK=6; fi',
                'if [ "${CANCEL_TASK}" = "speed_bounded" ]; then BWD_FLAG=""; fi',
                'if [ "${CANCEL_TASK}" = "speed_bounded" ]; then NEED_MIN=0; fi')
    for line, after in zip(original, override):
        assert src.count(line) == 1 and src.count(after) == 1
        assert src.index(after) > src.index(line), "the override must follow the original line"
    assert src.count('BWD_FLAG="--backward-per-group"') == 1 and src.count("NEED_MIN=120") == 1
    # and the three resolve as the speed task's when the script runs with the bounded task
    def resolve(task):
        head = src.split("# >>> manifest-parse")[0]
        start = head.index('MAXTOK="${CANCEL_MAX_NEW_TOKENS:-}"')
        end = head.index('echo "[cancel] exp=')
        need = src[src.index("NEED_MIN=0"):src.index('LIMIT_MIN="$(')]
        script = "\n".join([f"CANCEL_TASK={task}", "CANCEL_MAX_NEW_TOKENS=", head[start:end], need,
                            'printf "%s|%s|%s\\n" "$MAXTOK" "$BWD_FLAG" "$NEED_MIN"'])
        p = subprocess.run(["bash", "-c", script], capture_output=True, text=True)
        assert p.returncode == 0, p.stderr
        return p.stdout.strip()
    assert resolve("speed") == resolve("speed_bounded") == "6||0"
    assert resolve("capacity") == "128|--backward-per-group|120"


