    src = open(SBATCH).read()
    v2, v3, v4, v1 = _branches()
    for flag in FLAGS:
        assert flag in v2, f"the v2 branch does not pass {flag}"
        assert flag in v3, f"the v3 branch does not pass {flag}"
        assert flag in v4, f"the v4 branch does not pass {flag}"
        assert flag not in v1, f"a v1 branch passes {flag}"
        # Three until 2026-11-06, when the v4 branch of the ICML 2027 blocks (November 2026) joined the
        # v2 and v3 branches as the third place the three remedy flags are named.
        assert src.count(flag) == 3, f"{flag} appears outside the v2, v3 and v4 branches"
    assert "--keep-schedule" in v3 and src.count("--keep-schedule") == 1, \
        "only the v3 branch may pass the keep schedule"
    for flag in V4_FLAGS:
        assert flag in v4, f"the v4 branch does not pass {flag}"
        assert src.count(flag) == 1, f"{flag} appears outside the v4 branch"
    assert "--keep-schedule" not in v4
    launch = src[src.index('"${PY}" train_speed_grpo.py'):]
    assert "${REMEDY_FLAGS}" in launch.split("RC=$?")[0]
    # the capacity wall-clock guard still sits before the launch
    assert "NEED_MIN=120" in src and src.index("REFUSED: task") < src.index('"${PY}" train_speed_grpo.py')
    assert re.search(r'IFS=, read -r TASK_ID REGIME ARM_NAME ARM W SEED <<< "\$\{row\}"', v1)
    assert re.search(r'IFS=, read -r TASK_ID REGIME ARM_NAME ARM W W_TASK VMAX SEED <<< "\$\{row\}"', v1)


